/** Deterministic, idempotent catalogue migration; changes no player data or permissions. */
import { readFile, writeFile } from "node:fs/promises";
const catalog = JSON.parse(await readFile(new URL("../src/game/catalog.json", import.meta.url), "utf8"));
const rows = [...catalog.items, ...catalog.surfaces]
  .map((e) =>
    [
      e.id,
      e.tier,
      e.rarity,
      e.kind ?? "",
      e.zones?.join(",") ?? "",
      e.size ?? "",
      e.palettes?.length ?? "",
      e.season?.from ?? "",
      e.season?.to ?? "",
    ].join("|")
  )
  .join("\n");
const sql = `-- Brownstone catalogue, generated by scripts/export-catalog-sql.mjs.
-- Safe to reapply; keeps all existing residents, layouts, unlocks and reactions.
BEGIN;
WITH rows AS (
 SELECT string_to_array(line,'|') AS v, n-1 AS ordinal
 FROM unnest(string_to_array($catalog$${rows}$catalog$,E'\\n')) WITH ORDINALITY AS r(line,n)
)
INSERT INTO flats_private.catalog(id,ordinal,data)
SELECT v[1],ordinal,jsonb_strip_nulls(jsonb_build_object(
 'id',v[1],'tier',v[2]::int,'rarity',v[3],'kind',nullif(v[4],''),
 'zones',CASE WHEN v[5]<>'' THEN to_jsonb(string_to_array(v[5],',')) END,
 'size',nullif(v[6],'')::int,'paletteCount',nullif(v[7],'')::int,
 'season',CASE WHEN v[8]<>'' THEN jsonb_build_object('from',v[8]::int,'to',v[9]::int) END)) FROM rows
ON CONFLICT(id) DO UPDATE SET ordinal=excluded.ordinal,data=excluded.data;
COMMIT;
SELECT count(*) AS catalogue_entries, count(*) FILTER(WHERE data ? 'zones') AS things,
 count(*) FILTER(WHERE data ? 'kind') AS surfaces FROM flats_private.catalog;
`;
await writeFile(new URL("../supabase/migrations/003_brownstone_catalog.sql", import.meta.url), sql);
